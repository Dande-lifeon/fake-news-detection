"""Write a Markdown record of the current development environment.

Usage:
    python scripts/env_report.py --output docs/environment.md
"""

from __future__ import annotations

import argparse
import os
import platform
import sys
from datetime import date
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

PACKAGES = [
    "pandas",
    "numpy",
    "scipy",
    "scikit-learn",
    "pyarrow",
    "PyYAML",
    "matplotlib",
    "joblib",
    "requests",
    "pytest",
    "ruff",
    "kagglehub",
    "datasketch",
    "torch",
    "transformers",
]


def _version(name: str) -> str:
    try:
        return version(name)
    except PackageNotFoundError:
        return "not installed"


def _gpu() -> str:
    try:
        import torch
    except ImportError:
        return "not available (torch not installed)"
    if not torch.cuda.is_available():
        return "CPU only"
    return f"{torch.cuda.get_device_name(0)} (CUDA {torch.version.cuda})"


def build_report() -> str:
    rows = "\n".join(f"| `{name}` | {_version(name)} |" for name in PACKAGES)
    return f"""# Environment record

Generated by `python scripts/env_report.py` on {date.today().isoformat()}.

## Reference machine

| Item | Value |
|---|---|
| OS | {platform.platform()} |
| Architecture | {platform.machine()} |
| CPU | {platform.processor() or "unknown"} ({os.cpu_count()} logical cores) |
| Python | {sys.version.split()[0]} |
| GPU | {_gpu()} |

## Python packages

| Package | Version |
|---|---|
{rows}

## Install

```bash
python -m venv .venv
# Windows: .venv\\Scripts\\activate
# macOS/Linux: source .venv/bin/activate
pip install -e ".[dev]"
```

Optional neural models:

```bash
pip install -e ".[dev,neural]"
```

Conda users can create the base environment with `conda env create -f environment.yml`,
then run `pip install -e ".[dev]"` inside it.

## Verification

```bash
python -m pytest -q
python -m ruff check .
python -m fakenews.train.classical --config configs/base.yaml --model lr --smoke
```

The pinned package set is in `requirements.txt`; it was generated on Python 3.11.
The project requires Python 3.11 or newer.
"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Record the current environment")
    parser.add_argument("--output", type=Path, default=None, help="write Markdown to this path")
    args = parser.parse_args()

    report = build_report()
    if args.output is None:
        print(report)
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(report, encoding="utf-8")
        print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
